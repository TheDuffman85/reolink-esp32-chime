"""Generate deterministic gzip pages and a flash-resident C++ header."""
import gzip
import io
from pathlib import Path
import re


def pages(source):
    matches = re.findall(
        r'static const char (WebUi|LoginUi)\[\] PROGMEM = R"HTML\((.*?)\)HTML";',
        source, re.DOTALL,
    )
    if len(matches) != 2 or {name for name, _ in matches} != {"WebUi", "LoginUi"}:
        raise ValueError("WebUi.h must contain exactly one WebUi and one LoginUi HTML literal")
    return {name: html.encode("utf-8") for name, html in matches}


def compress(data):
    output = io.BytesIO()
    # No filename, timestamps or host-specific gzip header fields.
    with gzip.GzipFile(fileobj=output, mode="wb", filename="", mtime=0, compresslevel=9) as stream:
        stream.write(data)
    return output.getvalue()


def write_changed(path, content):
    if not path.exists() or path.read_bytes() != content:
        path.write_bytes(content)


def generate(source, destination):
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    header = ["// Generated by tools/build_web_ui.py; edit include/WebUi.h instead.",
              "#pragma once", "#include <Arduino.h>", ""]
    sizes = {}
    for name, data in pages(Path(source).read_text(encoding="utf-8")).items():
        compressed = compress(data)
        write_changed(destination / (name + ".html.gz"), compressed)
        header.append(f"static const uint8_t {name}Gzip[] PROGMEM = {{")
        for start in range(0, len(compressed), 16):
            header.append("  " + ",".join(f"0x{value:02x}" for value in compressed[start:start + 16]) + ",")
        header.extend(["};", ""])
        sizes[name] = (len(data), len(compressed))
    write_changed(destination / "WebUiGzip.h", "\n".join(header).encode("ascii"))
    return sizes
